import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CITIES, computeCityStats } from '../src/cities/index';

const out: Record<string, ReturnType<typeof computeCityStats>> = {};
for (const city of CITIES) {
  const t = Date.now();
  out[city.id] = computeCityStats(city);
  console.log(`${city.name}: ${out[city.id]!.totalCells} cells in ${Date.now() - t} ms`);
}

const body =
  `// Generated by scripts/generate-city-stats.ts. Do not edit by hand.\n` +
  `import type { CityStats } from './types';\n\n` +
  `export const CITY_STATS: Record<string, CityStats> = ${JSON.stringify(out, null, 2)};\n`;

writeFileSync(fileURLToPath(new URL('../src/cities/stats.generated.ts', import.meta.url)), body);
console.log('Wrote src/cities/stats.generated.ts');
